init_db()

class PromptRequest(BaseModel):
    user_id: str
    prompt: str

@app.post("/v1/chat")
def route_prompt(request: PromptRequest):
    conn = sqlite3.connect("cache.db")
    cursor = conn.cursor()
    
    # 1. Fetch all stored prompts and responses from the database
    cursor.execute("SELECT prompt_text, response_text FROM semantic_cache")
    rows = cursor.fetchall()
    
    best_similarity = 0.0
    matched_response = None
    
    # Encode current user prompt into a vector
    current_embedding = model.encode(request.prompt, convert_to_tensor=True)
    
    if rows:
        stored_prompts = [row[0] for row in rows]
        stored_responses = [row[1] for row in rows]
        
        # Encode stored prompts
        stored_embeddings = model.encode(stored_prompts, convert_to_tensor=True)
        
        # Calculate cosine similarity
        cos_scores = util.cos_sim(current_embedding, stored_embeddings)[0]
        
        best_idx = int(cos_scores.argmax())
        best_similarity = float(cos_scores[best_idx])
        
        # If similarity is higher than 80% (0.8), use cached response
        if best_similarity > 0.8:
            matched_response = stored_responses[best_idx]
            
    if matched_response:
        # Cache Hit!
        conn.close()
        return {
            "user_id": request.user_id,
            "prompt": request.prompt,
            "similarity": round(best_similarity, 2),
            "cached_response": matched_response,
            "source": "cache"
        }
    else:
        # Cache Miss: Generate a smart local response
        generated_answer = f"Response to your prompt: '{request.prompt}'. (Generated by local AI router)"
        
        # Save new prompt and generated response to the database cache
        cursor.execute(
            "INSERT INTO semantic_cache (prompt_text, response_text) VALUES (?, ?)",
            (request.prompt, generated_answer)
        )
        conn.commit()
        conn.close()
        
        return {
            "user_id": request.user_id,
            "prompt": request.prompt,
            "similarity": round(best_similarity, 2),
            "cached_response": generated_answer,
            "source": "generated_and_cached"
        }
class PromptRequest(BaseModel):
    user_id: str
    prompt: str

@app.post("/v1/chat")
async def route_prompt(req: PromptRequest):
    start_time = time.time()
    user_prompt = req.prompt.strip()
    new_vector = model.encode(user_prompt, convert_to_tensor=True)

    conn = sqlite3.connect("cache.db")
    cursor = conn.cursor()
    cursor.execute("SELECT id, prompt_text, response_text FROM semantic_cache")
    records = cursor.fetchall()
    conn.close()

    best_match_response = None
    highest_similarity = 0.0

    for rec_id, cached_prompt, cached_response in records:
        cached_vector = model.encode(cached_prompt, convert_to_tensor=True)
        similarity = util.cos_sim(new_vector, cached_vector).item()

        if similarity > highest_similarity:
            highest_similarity = similarity
            best_match_response = cached_response

    return {
        "user_id": req.user_id,
        "prompt": user_prompt,
        "similarity": highest_similarity,
        "cached_response": best_match_response
    }